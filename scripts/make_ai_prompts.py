"""Write AI_Prompts.docx: the disclosure of AI assisted development and every prompt the product itself sends to a model.

    python scripts/make_ai_prompts.py

The production prompt, the user message template and the JSON schemas are imported from the code, so the document
shows what the program really sends and cannot drift from it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from docx import Document  # noqa: E402
from docx.enum.text import WD_BREAK  # noqa: E402
from docx.shared import Pt, RGBColor  # noqa: E402

from docintel.extraction.llm import SYSTEM_PROMPT, build_user_message, invoice_schema  # noqa: E402

doc = Document()
base = doc.styles["Normal"]
base.font.name = "Calibri"
base.font.size = Pt(11)


def para(text: str, bold: bool = False, italic: bool = False) -> None:
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    p.paragraph_format.space_after = Pt(6)


def bullets(items: list[str]) -> None:
    for t in items:
        doc.add_paragraph(t, style="List Bullet")


def code(text: str) -> None:
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.name = "Consolas"
    r.font.size = Pt(9)
    r.font.color.rgb = RGBColor(0x20, 0x20, 0x20)
    p.paragraph_format.left_indent = Pt(10)
    p.paragraph_format.space_after = Pt(8)


doc.add_heading("AI prompts and disclosure of AI assisted development", 0)
para("Project: AI-Powered Document Intelligence System, home assessment for the Senior AI Engineer role at Care Guide BD.")
para("Author: Raiyan Sayeed")

doc.add_heading("Disclosure", 1)
para("This project was built with AI assistance, and most of the code was written by an AI. Here is what that means in practice.")
bullets(
    [
        "Tool: Claude, made by Anthropic, used as a coding assistant over several days (through Claude Code and the Claude app). The model version changed during the work; the last one was Claude Sonnet 5.5.",
        "What Claude did: wrote the backend (document readers, OCR pipeline, extraction rules, validation, job queue, REST API, search), the React front end, the automated tests, the synthetic data generator and the evaluation scripts, and this documentation. It ran the tests and the evaluations in its own sandbox and reported what it measured.",
        "What I did: I gave Claude the assessment brief and the email, set the rules it had to work under (report only numbers that were measured, say plainly that the test data is synthetic and where the method is weak, claim nothing that was not run), decided scope with it, and I am the one submitting this work and answerable for it.",
        "AI inside the product is optional. With no API key the system never calls an AI service and extraction is done by rule based code. With a Gemini or OpenAI key, a model reads the document text under the prompts in Part A. That path was tested against a mock server only, because the environment the code was built in could not reach those services. Every accuracy figure in EVALUATION.md comes from the offline rules extractor, and I report no figure for the model path.",
        "The test documents are synthetic and were generated by code written in the same working session as the extractor. EVALUATION.md explains what that does to the numbers.",
    ]
)

doc.add_heading("Part A. Prompts the system sends to a model", 1)
para("These are used only when a Gemini or OpenAI key is configured. They are printed from the program itself (docintel/extraction/llm.py), not retyped.")

doc.add_heading("A1. System prompt", 2)
code(SYSTEM_PROMPT)

doc.add_heading("A2. User message", 2)
para("The text of the document (or of a chunk of it, for long documents) goes between document tags. A second call asks for the line items only when a long document is cut into pieces. Example with a placeholder for the text:")
code(build_user_message("<text of the document, page layout kept>"))
code(build_user_message("<text of one chunk>", items_only=True))

doc.add_heading("A3. Required answer format", 2)
para("The model must answer with JSON that matches a strict schema. Every field carries its value and an evidence quote. Shown here is the OpenAI style strict schema; the Gemini request uses the same structure in Gemini's schema dialect (upper case type names and a nullable flag).")
code(json.dumps(invoice_schema("openai"), indent=2))

doc.add_heading("A4. How the answer is checked before it is used", 2)
bullets(
    [
        "Grounding: each non null value must come with a quote that occurs in the document text, and the value must be readable from that quote. A value that fails is dropped and reported as UNGROUNDED_VALUE. A model that invents a total cannot put it in the database.",
        "Personal data is masked before sending: emails, phone numbers, IBANs, bank account numbers and card numbers that pass the card checksum. Best effort.",
        "The document text is treated as untrusted. The system prompt tells the model to ignore instructions found in it, but the real protection is the grounding check and the fixed schema, not that request.",
        "Merging with the rules extractor: agreement raises confidence; for money fields the reading that makes subtotal plus tax equal total wins; other disagreements are kept with lowered confidence and shown to a person as EXTRACTOR_DISAGREEMENT.",
        "Failures: calls retry with backoff and honour Retry-After; after repeated failures a circuit breaker stops calling the service for a while and the rules result is used on its own.",
    ]
)

doc.add_heading("Part B. Instructions I gave Claude while building", 1)
para("The work was one long conversation spread over several days. Quoted text below is exact; descriptions are marked as such. Short messages such as corrections and requests to continue are left out. The very first message, where I attached the assessment PDF and the email, is not reproduced word for word here.", italic=True)

doc.add_heading("B1. The request", 2)
para("I attached the assessment PDF (Senior AI Engineer, AI-Powered Document Intelligence System) and the email, and asked Claude to build the whole project. In my words, to build it \"fully and completely by thoroughly following the instructions given in the home assessment PDF\" and the email.")

doc.add_heading("B2. Rules I set for how it should work (described, not quoted)", 2)
bullets(
    [
        "Follow the brief exactly: all seven tasks, all deliverables.",
        "Never overclaim. Only report numbers that were measured. Label synthetic data as synthetic and say where the method is weak.",
        "Say plainly what was cut or could not be tested (for example the AI path against the real services, and Docker).",
        "Write documentation and messages in plain human prose, and never use dashes as punctuation.",
        "Do not touch the earlier API monitor assignment, which was already submitted.",
    ]
)

doc.add_heading("B3. Instructions about time, quoted", 2)
for q in [
    "It's 31 October, 2026, 8:00 pm now. And I have to submit it by 1 November at 2:35 am. So, please complete the project fully and completely within that timeframe as quickly as possible and as soon as possible. Please continue exactly from where you left off previously.",
    "It's 1 November 2026, 1:00 am now. And I have to submit it by 1 November at 2:35 am. So, please complete the project fully and completely within that timeframe as quickly as possible and as soon as possible. Please continue exactly from where you left off previously.",
    "Please continue exactly from where you left off previously. And It's 1 November 2026, 11:00 am now. And I have to submit it by the end of the day, record the video, etc. So, please complete the project fully and completely as quickly as possible and as soon as possible.",
]:
    p = doc.add_paragraph(style="Intense Quote")
    p.add_run(q)

doc.add_paragraph().add_run().add_break(WD_BREAK.LINE)
para("The code, tests and documents in the repository are the record of what the AI produced from these instructions. Everything in them can be checked by running the commands in README.md.")

out = ROOT / "AI_Prompts.docx"
doc.save(out)
print("wrote", out)
