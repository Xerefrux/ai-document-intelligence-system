"""Generate docs/DATABASE.md and docs/API.md from the code, so they cannot drift from it.

    python scripts/gen_docs.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from docintel.api.app import create_app  # noqa: E402
from docintel.config import Settings  # noqa: E402
from docintel.db.models import Base  # noqa: E402

COLUMN_NOTES = {
    ("documents", "sha256"): "hash of the file bytes; identical uploads are recognised by it",
    ("documents", "status"): "queued, processing, completed, failed, cancelled",
    ("documents", "review_status"): "none, needs_review, ok, corrected, approved (worst state of its records)",
    ("documents", "duplicate_of"): "id of the earlier document with the same content or the same invoice",
    ("records", "fields_json"): "every field with confidence, evidence text, page, source and notes",
    ("records", "search_text"): "text indexed by the record_fts full text table",
    ("records", "inv_key"): "normalised invoice number, used for duplicate checks and cross verification",
    ("records", "dedupe_key"): "supplier + date + total, used to find possible duplicates",
    ("records", "version"): "bumped on every edit; the API refuses an edit made on an old version",
    ("records", "method"): "rules, llm or hybrid",
    ("pages", "source"): "text_layer, ocr, sheet or failed",
    ("jobs", "status"): "queued, running, succeeded, failed, cancelled",
    ("jobs", "run_after"): "a retried job waits until this time (exponential backoff)",
    ("jobs", "heartbeat_at"): "a running job with an old heartbeat is put back in the queue",
    ("embeddings", "vector"): "float32 array stored as bytes",
    ("validation_issues", "record_id"): "null for problems with the whole document",
}


def database_doc() -> str:
    out = ["# Database schema", "", "Generated by `scripts/gen_docs.py` from the SQLAlchemy models in `docintel/db/models.py`. Do not edit by hand.", ""]
    out += [
        "SQLite is the database that is tested. It runs in WAL mode (readers do not block the writer) with foreign keys on. "
        "Keyword search uses two FTS5 virtual tables, `page_fts` (over `pages.text`) and `record_fts` (over `records.search_text`). "
        "They are external content tables: they hold the index only, the text stays in the original table, and triggers keep them in sync. "
        "The models use portable types, so another SQL database can be pointed at with `DOCINTEL_DATABASE_URL`, "
        "but only SQLite was run (see docs/LIMITATIONS.md).",
        "",
        "## Relationships",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for t in Base.metadata.sorted_tables:
        for c in t.columns:
            for fk in c.foreign_keys:
                out.append(f"    {fk.column.table.name} ||--o{{ {t.name} : \"{c.name}\"")
    for t in Base.metadata.sorted_tables:
        out.append(f"    {t.name} {{")
        for c in t.columns:
            kind = str(c.type).split("(")[0].lower()
            tag = " PK" if c.primary_key else (" FK" if c.foreign_keys else "")
            out.append(f"        {kind} {c.name}{tag}")
        out.append("    }")
    out += ["```", "", "`embeddings.owner_id` points at a record or a page (see `owner_type`), so it has no foreign key of its own; its `document_id` column cascades with the document.", ""]
    out += ["## Tables", ""]
    for t in Base.metadata.sorted_tables:
        out += [f"### {t.name}", "", "| Column | Type | Null | Notes |", "|---|---|---|---|"]
        for c in t.columns:
            notes = []
            if c.primary_key:
                notes.append("primary key")
            for fk in c.foreign_keys:
                notes.append(f"references {fk.column.table.name}.{fk.column.name}")
            extra = COLUMN_NOTES.get((t.name, c.name))
            if extra:
                notes.append(extra)
            out.append(f"| {c.name} | {str(c.type)} | {'yes' if c.nullable else 'no'} | {'; '.join(notes)} |")
        if t.indexes:
            out += ["", "Indexes: " + ", ".join(f"`{ix.name}` ({', '.join(col.name for col in ix.columns)})" for ix in sorted(t.indexes, key=lambda i: i.name))]
        out.append("")
    return "\n".join(out) + "\n"


def api_doc() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app(Settings(data_dir=Path(tmp), workers=0, _env_file=None), start_workers=False)
        spec = app.openapi()
    out = ["# API reference", "", "Generated by `scripts/gen_docs.py` from the running application. The same information, with request and response schemas and a way to try each call, is served at `/api/docs` while the server runs.", ""]
    out += [
        "## Conventions",
        "",
        "- Everything is under `/api`. Timestamps are UTC, ISO 8601 with a trailing `Z`.",
        "- Authentication: when `DOCINTEL_API_KEY` is set, send it as `X-API-Key: <key>` or `Authorization: Bearer <key>`. `/api/health` stays public.",
        "- Errors always have this shape, with a stable `code` for programs and a `message` written for people: `{\"error\": {\"code\": \"VERSION_CONFLICT\", \"message\": \"...\", \"details\": {}}}`.",
        "- Lists take `limit` and `offset` and return `{items, total, limit, offset}`.",
        "- Editing a record takes an optional `expected_version`. If someone else saved first the answer is `409 VERSION_CONFLICT` instead of a silent overwrite.",
        "- Reprocessing a document that has manual corrections answers `409 CORRECTIONS_WOULD_BE_LOST` unless the request says `confirm: true`.",
        "- Too many requests from one client answer `429 RATE_LIMITED` with a `Retry-After` header.",
        "",
        "## Endpoints",
        "",
        "| Method | Path | What it does |",
        "|---|---|---|",
    ]
    order = {"get": 0, "post": 1, "patch": 2, "put": 3, "delete": 4}
    for path, ops in sorted(spec["paths"].items()):
        for method, op in sorted(ops.items(), key=lambda kv: order.get(kv[0], 9)):
            if method in order:
                out.append(f"| {method.upper()} | `{path}` | {(op.get('summary') or '').strip()} |")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "DATABASE.md").write_text(database_doc(), encoding="utf-8")
    (docs / "API.md").write_text(api_doc(), encoding="utf-8")
    print("wrote docs/DATABASE.md and docs/API.md")


if __name__ == "__main__":
    main()
